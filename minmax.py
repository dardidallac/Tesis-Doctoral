def gettAIByWIndow(seq,wsDict,windowSize):
  tAI = []
  windowCenter = []
  codons = re.findall('...', str(seq))
  #
  gaps = [i for i in range(len(codons)) if codons[i] == '---']
  gaplessCodons = re.findall('...',re.sub('-','',seq))
  #
  clen = len(gaplessCodons)
  centerOfWindow=math.ceil(windowSize/2)
  for i in range(clen):
    start = i-centerOfWindow+1
    if start < 0:
      start=0
    end = i+centerOfWindow
    seqWin = gaplessCodons[start:end]
    tAI.append(stats.gmean([wsDict[c] for c in seqWin if c not in ['ATG','TAA','TAG','TGA']]))
    windowCenter.append(i)
  for i in gaps:
    if i > 0:
      tAI.insert(i,np.float64(tAI[i-1]))
    else:
      tAI.insert(i,np.float64(0))
  return(tAI,codons)

