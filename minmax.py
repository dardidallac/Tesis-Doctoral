def readfreqTb(cufn):
  '''Reads codon usage table in NCBI format. Absolute codon counts / 1000.'''
  with open(cufn,'r') as cuf:
    frequenceTb = {}
    for l in cuf:
      l = l.replace('U','T').strip()
      l = l.split('\t')
      if len(l) > 1:
        for i in range(0,len(l),3):
          frequenceTb[l[i]] = float(l[i+1])
  if not len(frequenceTb) == 64:
    with open(cufn,'r') as cuf:
      frequenceTb = {}
      for l in cuf:
        import re
        l = l.replace('U','T').strip().upper()
        l = re.sub(r'([ATCG]{3} +[^(]+)(\( *[^)]*\))', '\\1', l)
        l = l.split()
        if len(l) > 1:
          for i in range(0,len(l),2):
            frequenceTb[l[i]] = float(l[i+1])
  if not len(frequenceTb) == 64:
    print('Error with the frequence table...')
  return(frequenceTb)

def getmaxFreqTB(frequenceTb,aaCodonDict):
  maxFreqTB = {}
  minFreqTB = {}
  avgFreqTB = {}
  for aa in aaCodonDict:
    if aa != None:
      codonfreqs = []
      for codon in aaCodonDict[aa]:
        codonfreqs.append(frequenceTb[codon])
      codonfreqs = np.array(codonfreqs)
      maxFreqTB[aa] = np.max(codonfreqs)
      minFreqTB[aa] = np.min(codonfreqs)
      avgFreqTB[aa] = np.round(np.mean(codonfreqs),3)
  return(maxFreqTB,minFreqTB,avgFreqTB)


def minMax(id,sequence,windowSize,frequenceTb,maxFreqTB,minFreqTB,avgFreqTB):
  """Calculates %MinMax as in Clarke T.F. & Clark P.L. (2008) Rare Codons Cluster PLoS ONE 3: e3412.
  Input: codon list
  Output: %MinMax value
  Credit: Derived from https://github.com/chowington/minmax
  """
  if not len(sequence)%3 == 0:
    print(f'Not a coding sequence. The number of nucleotides is not a multiple of 3: {len(sequence)}.')
    return(None,None)
  #
  codons = re.findall('...',sequence)
  #map gap positions
  gaps = [i for i in range(len(codons)) if codons[i] == '---']
  gaplessCodons = re.findall('...',re.sub('-','',sequence))
  minMaxValues = []
  #add 0 values for first positions in which a complete windows is not possible
  #calculate minmax for each window.
  #print(f'The gene {id} has {len(codons)} codons.')
  for i in range(len(gaplessCodons)):
    window = gaplessCodons[i-int(windowSize/2):i+int(windowSize/2)+1]
    if len(window) != windowSize:
      minMaxValues.append(np.float64(0))
      continue
    cfreqs = []
    maxFreqs = []
    minFreqs = []
    avgFreqs = []
    for wc in window:
      if wc in codonDict and wc in frequenceTb and wc not in ['TAA','TGA','TAG']:
        aa = codonDict[wc]
        cfreqs.append(frequenceTb[wc])
        maxFreqs.append(maxFreqTB[aa])
        minFreqs.append(minFreqTB[aa])
        avgFreqs.append(avgFreqTB[aa])
    #
    cfreqs = np.array(cfreqs)
    maxFreqs = np.array(maxFreqs)
    minFreqs = np.array(minFreqs)
    if len(cfreqs) > 0:
      maxvalue = (np.sum(cfreqs) - np.sum(avgFreqs))/(np.sum(maxFreqs) - np.sum(avgFreqs))*100
      minvalue = (np.sum(avgFreqs) - np.sum(cfreqs))/(np.sum(avgFreqs) - np.sum(minFreqs))*100
    else:
      maxvalue = 0
      minvalue = 0
    if maxvalue >= 0:
      minMaxValues.append(round(maxvalue,2))
    else:
      minMaxValues.append(-round(minvalue,2))
  for i in gaps:
    if i > 0:
      minMaxValues.insert(i,np.float64(minMaxValues[i-1]))
    else:
      minMaxValues.insert(i,np.float64(0))
  return(codons,minMaxValues)

