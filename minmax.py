def extract_proteins_and_cds(gf):
  protDict = {}
  cdsDict = {}
  for r in SeqIO.parse(gf, "gb"):
    for feature in r.features:
      if feature.type == "CDS":
        if 'locus_tag' in feature.qualifiers:
          name = feature.qualifiers['locus_tag'][0]
        elif 'gene' in feature.qualifiers:
          name = feature.qualifiers['gene'][0]
        elif 'protein_id' in feature.qualifiers:
          name = feature.qualifiers['protein_id'][0]
        else:
          continue
        if 'translation' in feature.qualifiers:
          aaseq = feature.qualifiers['translation'][0]
          location = feature.location
          nucseq = location.extract(r).seq
          if len(nucseq) % 3 != 0:
            continue
          if len(aaseq) < 80:
            continue
          protDict[name] = aaseq
          cdsDict[name] = str(nucseq[:-3]).upper()
  return(protDict,cdsDict)

